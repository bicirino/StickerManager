
CREATE TABLE usuarios (
  id INT AUTO_INCREMENT PRIMARY KEY,
  nome VARCHAR(100) NOT NULL,
  email VARCHAR(150) NOT NULL UNIQUE,
  senha_hash VARCHAR(255) NOT NULL,
  is_admin TINYINT(1) NOT NULL DEFAULT 0,
  criado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE categoria (
  id INT AUTO_INCREMENT PRIMARY KEY,
  nome VARCHAR(60) NOT NULL UNIQUE,
  descricao VARCHAR(255)
) ENGINE=InnoDB;

CREATE TABLE selecoes (
  id INT AUTO_INCREMENT PRIMARY KEY,
  nome VARCHAR(80) NOT NULL UNIQUE,
  sigla VARCHAR(5) NOT NULL,
  confederacao VARCHAR(40) NOT NULL
) ENGINE=InnoDB;

CREATE TABLE posicao (
  id INT AUTO_INCREMENT PRIMARY KEY,
  nome VARCHAR(30) NOT NULL UNIQUE
) ENGINE=InnoDB;

CREATE TABLE figurinhas (
  id INT AUTO_INCREMENT PRIMARY KEY,
  numero VARCHAR(10) NOT NULL,
  nome_jogador VARCHAR(120) NOT NULL,
  categoria_id INT NOT NULL,
  selecao_id INT NULL,
  posicao_id INT NULL,
  raridade ENUM('Comum','Especial','Lendária') NOT NULL DEFAULT 'Comum',
  FOREIGN KEY (categoria_id) REFERENCES categoria(id),
  FOREIGN KEY (selecao_id) REFERENCES selecoes(id),
  FOREIGN KEY (posicao_id) REFERENCES posicao(id),
  UNIQUE KEY uk_numero (numero)
) ENGINE=InnoDB;

CREATE TABLE minha_colecao (
  id INT AUTO_INCREMENT PRIMARY KEY,
  usuario_id INT NOT NULL,
  figurinha_id INT NOT NULL,
  quantidade INT NOT NULL DEFAULT 1,
  atualizado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE,
  FOREIGN KEY (figurinha_id) REFERENCES figurinhas(id) ON DELETE CASCADE,
  UNIQUE KEY uk_user_fig (usuario_id, figurinha_id)
) ENGINE=InnoDB;

